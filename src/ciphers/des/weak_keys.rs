//! Weak and semi-weak DES keys, as listed in NIST SP 800-67 Rev. 2 section 3.3.2.
//!
//! A weak key gives the same round key in all 16 rounds, so encrypting twice with
//! it returns the plaintext. A semi-weak key has a partner key that decrypts what
//! it encrypts. The keys are listed with odd parity, but [`is_weak`] ignores the
//! parity bits, as the key schedule does. [`DesCipher::new`](super::DesCipher)
//! doesn't refuse these keys.

/// The 4 weak keys.
pub const WEAK_KEYS: [[u8; 8]; 4] = [
    [0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01],
    [0xFE, 0xFE, 0xFE, 0xFE, 0xFE, 0xFE, 0xFE, 0xFE],
    [0xE0, 0xE0, 0xE0, 0xE0, 0xF1, 0xF1, 0xF1, 0xF1],
    [0x1F, 0x1F, 0x1F, 0x1F, 0x0E, 0x0E, 0x0E, 0x0E],
];

/// The 12 semi-weak keys, in pairs: entries `2 * i` and `2 * i + 1` each decrypt
/// what the other encrypts.
pub const SEMI_WEAK_KEYS: [[u8; 8]; 12] = [
    [0x01, 0x1F, 0x01, 0x1F, 0x01, 0x0E, 0x01, 0x0E],
    [0x1F, 0x01, 0x1F, 0x01, 0x0E, 0x01, 0x0E, 0x01],
    [0x01, 0xE0, 0x01, 0xE0, 0x01, 0xF1, 0x01, 0xF1],
    [0xE0, 0x01, 0xE0, 0x01, 0xF1, 0x01, 0xF1, 0x01],
    [0x01, 0xFE, 0x01, 0xFE, 0x01, 0xFE, 0x01, 0xFE],
    [0xFE, 0x01, 0xFE, 0x01, 0xFE, 0x01, 0xFE, 0x01],
    [0x1F, 0xE0, 0x1F, 0xE0, 0x0E, 0xF1, 0x0E, 0xF1],
    [0xE0, 0x1F, 0xE0, 0x1F, 0xF1, 0x0E, 0xF1, 0x0E],
    [0x1F, 0xFE, 0x1F, 0xFE, 0x0E, 0xFE, 0x0E, 0xFE],
    [0xFE, 0x1F, 0xFE, 0x1F, 0xFE, 0x0E, 0xFE, 0x0E],
    [0xE0, 0xFE, 0xE0, 0xFE, 0xF1, 0xFE, 0xF1, 0xFE],
    [0xFE, 0xE0, 0xFE, 0xE0, 0xFE, 0xF1, 0xFE, 0xF1],
];

/// Returns `true` if `key` is a weak or semi-weak key, whatever its parity bits.
///
/// # Examples
///
/// ```
/// use oes::ciphers::des::weak_keys::is_weak;
///
/// assert!(is_weak(&[0x01; 8]));
/// assert!(is_weak(&[0x00; 8])); // the same key with even parity
/// assert!(!is_weak(&[0x13, 0x34, 0x57, 0x79, 0x9B, 0xBC, 0xDF, 0xF1]));
/// ```
pub fn is_weak(key: &[u8; 8]) -> bool {
    let same_without_parity =
        |listed: &[u8; 8]| key.iter().zip(listed).all(|(a, b)| a & 0xFE == b & 0xFE);
    WEAK_KEYS
        .iter()
        .chain(&SEMI_WEAK_KEYS)
        .any(same_without_parity)
}
